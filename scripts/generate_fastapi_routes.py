#!/usr/bin/env python
"""Generate ``conf/k8s/fastapi-routes.yaml``, the list of paths FastAPI serves.

On Kubernetes the gateway (Envoy) sends each FastAPI route straight to the
FastAPI Service and everything else to web.py, so it needs the list of FastAPI
routes per method (see #14384). That list used to be hand-copied into the Helm
chart and went stale every time a route moved from web.py to FastAPI. This
script generates it from the app, and ``test_fastapi_routes.py`` fails CI when
the checked-in file is out of date.

Usage:
    python scripts/generate_fastapi_routes.py          # write the file
    python scripts/generate_fastapi_routes.py --check   # exit 1 if it is stale

Method matters (FastAPI serves ``POST /account/login`` but ``GET /account/login``
is still web.py) and path shape matters (``/works/OL1W/ratings.json`` is FastAPI,
``/works/OL1W.json`` is web.py), so every entry is one ``"METHOD [METHOD...] /path"``
string, the path in FastAPI syntax.

The exclusions below are an explicit list on purpose: route metadata can't drive
them. Real public routes are ``include_in_schema=False`` (e.g. ``/api/books``) or
tagged ``internal`` (e.g. ``/search/facets.json``), so a new tag just for this
would be easy to forget. To keep the list from rotting, the script fails if an
excluded path no longer exists.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import TYPE_CHECKING

from fastapi.routing import APIRoute
from starlette.routing import Mount, Route

if TYPE_CHECKING:
    from fastapi import FastAPI

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "conf" / "k8s" / "fastapi-routes.yaml"

HEADER = "# Generated by scripts/generate_fastapi_routes.py. Do not edit by hand.\n# Run `python scripts/generate_fastapi_routes.py` to regenerate.\n"

# Exact paths FastAPI serves but the gateway must not route to FastAPI. Every one
# must still exist in the app, or the script fails (so a renamed/removed route
# can't leave a dead exclusion behind).
EXCLUDED_PATHS = {
    # FastAPI's own docs and schema
    "/docs",
    "/docs/oauth2-redirect",
    "/redoc",
    "/openapi.json",
    # Infrastructure, not a user route
    "/metrics",
    "/health",
    "/static",  # the StaticFiles mount
    # Auth test routes (not real endpoints)
    "/account/test.json",
    "/account/protected.json",
    "/account/optional.json",
}

# Prefixes FastAPI serves but the gateway must not route to FastAPI. Each must
# still match at least one route.
EXCLUDED_PREFIXES = (
    "/status/",  # testing dashboard only
)

# The local dev / testing proxy fallback (and, later, the wiki document route).
# It is only registered in some environments, so its absence is not an error.
CATCH_ALL_PATH = "/{path:path}"


class RouteEntry:
    """One concrete route: its HTTP methods (minus HEAD), its path, whether it is an HTML page."""

    def __init__(self, methods: set[str], path: str, is_page: bool) -> None:
        self.methods = methods
        self.path = path
        self.is_page = is_page


def _walk(routes: list, is_page_class: type) -> list[RouteEntry]:
    """Collect every ``APIRoute``, recursing into included routers.

    ``app.include_router`` wraps each router in an ``_IncludedRouter`` whose real
    routes hang off ``original_router``; a plain walk of ``app.routes`` would find
    only the few top-level routes. ``Mount`` and plain ``Route`` objects (the
    ``/static`` mount, FastAPI's ``/docs`` etc.) carry no ``APIRoute`` metadata and
    are excluded by path anyway, so they are skipped here.
    """
    entries: list[RouteEntry] = []
    for route in routes:
        if hasattr(route, "original_router"):
            entries.extend(_walk(route.original_router.routes, is_page_class))
        elif isinstance(route, APIRoute):
            methods = {m for m in (route.methods or set()) if m != "HEAD"}
            entries.append(RouteEntry(methods, route.path, isinstance(route, is_page_class)))
    return entries


def _all_paths(routes: list) -> set[str]:
    """Every path in the app, including mounts and plain routes, for the exclusion check."""
    paths: set[str] = set()
    for route in routes:
        if hasattr(route, "original_router"):
            paths |= _all_paths(route.original_router.routes)
        elif isinstance(route, (APIRoute, Route, Mount)):
            paths.add(route.path)
    return paths


def _check_exclusions_exist(app: FastAPI) -> None:
    """Fail if an excluded path (or prefix) no longer matches a route, so the list can't rot."""
    paths = _all_paths(app.routes)
    missing = sorted(p for p in EXCLUDED_PATHS if p not in paths)
    if missing:
        raise SystemExit(f"Excluded paths no longer exist in the app: {', '.join(missing)}.\nUpdate EXCLUDED_PATHS in scripts/generate_fastapi_routes.py.")
    for prefix in EXCLUDED_PREFIXES:
        if not any(p.startswith(prefix) for p in paths):
            raise SystemExit(f"Excluded prefix {prefix!r} no longer matches any route.\nUpdate EXCLUDED_PREFIXES in scripts/generate_fastapi_routes.py.")


def _is_excluded(path: str) -> bool:
    return path in EXCLUDED_PATHS or path == CATCH_ALL_PATH or any(path.startswith(p) for p in EXCLUDED_PREFIXES)


def _format_entries(entries: list[RouteEntry]) -> list[str]:
    """Collapse the routes to one ``"METHOD [METHOD...] /path"`` string per path, sorted."""
    methods_by_path: dict[str, set[str]] = {}
    for entry in entries:
        if _is_excluded(entry.path):
            continue
        methods_by_path.setdefault(entry.path, set()).update(entry.methods)
    return [f"{' '.join(sorted(methods))} {path}" for path, methods in sorted(methods_by_path.items())]


def render_routes_yaml(app: FastAPI) -> str:
    """Return the full contents of ``conf/k8s/fastapi-routes.yaml`` for ``app``."""
    _check_exclusions_exist(app)
    all_entries = _walk(app.routes, _site_page_route_class())
    pages = _format_entries([e for e in all_entries if e.is_page])
    api = _format_entries([e for e in all_entries if not e.is_page])

    lines = [HEADER.rstrip("\n"), "fastapiRoutes:", "  # Pages (SitePageRoute)"]
    lines += [f"  - {entry}" for entry in pages]
    lines.append("  # JSON / API")
    lines += [f"  - {entry}" for entry in api]
    return "\n".join(lines) + "\n"


def _site_page_route_class() -> type:
    # Imported lazily so the exclusion constants can be read without building the app.
    from openlibrary.fastapi.shared.site_page import SitePageRoute  # noqa: PLC0415

    return SitePageRoute


def build_app() -> FastAPI:
    """Build the FastAPI app for route introspection.

    Uses the same ``create_app()`` the server and the tests use. Under pytest it
    builds without the legacy web.py stack (see ``create_app``); run as a script
    it needs the app's full dependencies, so run it where those exist (the test
    environment, or inside Docker: ``docker compose run --rm home python
    scripts/generate_fastapi_routes.py``).
    """
    from openlibrary.asgi_app import create_app  # noqa: PLC0415

    app = create_app()
    if app is None:  # create_app returns None on a repeated Sentry init
        raise SystemExit("create_app() returned None; cannot introspect routes.")
    return app


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit non-zero if the checked-in file is stale, without writing")
    args = parser.parse_args(argv)

    content = render_routes_yaml(build_app())

    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT} is stale. Run `python scripts/generate_fastapi_routes.py`.", file=sys.stderr)
            return 1
        print(f"{OUTPUT} is up to date.")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content)
    print(f"Wrote {OUTPUT} ({content.count('  - ')} routes).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
