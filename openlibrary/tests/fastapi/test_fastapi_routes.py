"""The checked-in FastAPI route list (conf/k8s/fastapi-routes.yaml) must match the app.

The gateway on Kubernetes routes each FastAPI path to FastAPI and everything else
to web.py, from this file (see #14384). It is generated by
scripts/generate_fastapi_routes.py, so it goes stale whenever a route moves. This
test fails when it does, with how to regenerate it.
"""

from fastapi import APIRouter, FastAPI

from scripts.generate_fastapi_routes import (
    OUTPUT,
    _format_entries,
    _walk,
    render_routes_yaml,
)


def _build_app() -> FastAPI:
    # Under pytest, create_app() builds the FastAPI app without the legacy web.py stack.
    from openlibrary.asgi_app import create_app  # noqa: PLC0415

    app = create_app()
    assert app is not None
    return app


def test_checked_in_route_file_is_current():
    expected = render_routes_yaml(_build_app())
    actual = OUTPUT.read_text()
    assert actual == expected, "conf/k8s/fastapi-routes.yaml is stale. Run `python scripts/generate_fastapi_routes.py`."


def test_excluded_paths_are_absent_from_the_file():
    content = OUTPUT.read_text()
    for excluded in ("/health", "/metrics", "/docs", "/openapi.json", "/account/test.json", "/status/"):
        assert f" {excluded}" not in content


def test_methods_on_one_path_are_grouped_and_sorted():
    router = APIRouter()

    @router.get("/thing.json")
    def _get() -> dict:
        return {}

    @router.post("/thing.json")
    def _post() -> dict:
        return {}

    app = FastAPI()
    app.include_router(router)
    entries = _format_entries([e for e in _walk(app.routes, type(None)) if not e.is_page])
    assert entries == ["GET POST /thing.json"]


def test_head_is_dropped():
    router = APIRouter()

    @router.get("/thing.json")
    def _get() -> dict:
        return {}

    app = FastAPI()
    app.include_router(router)
    entries = _format_entries(_walk(app.routes, type(None)))
    assert entries == ["GET /thing.json"]  # FastAPI adds HEAD for a GET route; it must not appear
